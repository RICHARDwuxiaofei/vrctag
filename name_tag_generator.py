def load_settings():
    settings = DEFAULTS.copy()
    path = HERE / 'settings.json'
    if path.exists():
        settings.update(json.loads(path.read_text(encoding='utf-8-sig')))
    return settings

def validate(name, status):
    name, status = name.strip(), status.strip()
    if not name or not status:
        raise ValueError('Name and status are required.')
    if len(name) > 80 or len(status) > 40:
        raise ValueError('Use up to 80 characters for name and 40 for status. Longer text prints smaller.')
    if any(ord(c) < 32 for c in name + status):
        raise ValueError('Use single-line text for name and status.')
    return name, status

def safe_stem(name, status):
    stem = re.sub(r'[<>:"/\\|?*\x00-\x1f]', '_', name + '_' + status).strip(' .')[:100]
    if stem.upper().split('.')[0] in {'CON','PRN','AUX','NUL', *['COM'+str(i) for i in range(1,10)], *['LPT'+str(i) for i in range(1,10)]}:
        stem = '_' + stem
    return stem or 'NameTag'

def make_text(bpy, name, text, x, y, width, height, font, mat):
    from mathutils import Vector
    import bmesh
    curve = bpy.data.curves.new(name, 'FONT')
    curve.body = text
    curve.font = font
    curve.size = 10
    curve.extrude = .25
    curve.resolution_u = 16
    curve.fill_mode = 'BOTH'
    obj = bpy.data.objects.new(name, curve)
    bpy.context.collection.objects.link(obj)
    bpy.ops.object.select_all(action='DESELECT')
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj
    bpy.ops.object.convert(target='MESH')
    obj = bpy.context.object
    if not obj.data.vertices:
        raise ValueError('Font could not generate text: ' + text)
    mins = [min(v.co[k] for v in obj.data.vertices) for k in range(3)]
    maxs = [max(v.co[k] for v in obj.data.vertices) for k in range(3)]
    scale = min(width / (maxs[0]-mins[0]), height / (maxs[1]-mins[1]))
    for v in obj.data.vertices:
        v.co = Vector((x+(v.co.x-mins[0])*scale, y+(v.co.y-mins[1])*scale, 2+v.co.z-mins[2]))
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    bmesh.ops.remove_doubles(bm, verts=list(bm.verts), dist=.0001)
    bmesh.ops.recalc_face_normals(bm, faces=list(bm.faces))
    bm.to_mesh(obj.data)
    bm.free()
    obj.data.update()
    obj.data.materials.append(mat)
    obj['text'] = text
    return obj, scale

def export_3mf(bpy, parts, path, title):
    namespace = 'http://schemas.microsoft.com/3dmanufacturing/core/2015/02'
    ET.register_namespace('', namespace)
    def sub(parent, tag, attributes=None):
        return ET.SubElement(parent, '{'+namespace+'}'+tag, attributes or {})
    root = ET.Element('{'+namespace+'}model', {'unit':'millimeter', '{http://www.w3.org/XML/1998/namespace}lang':'en-US'})
    sub(root, 'metadata', {'name':'Title'}).text = title
    sub(root, 'metadata', {'name':'BambuStudio:3mfVersion'}).text = '1'
    resources = sub(root, 'resources')
    materials = sub(resources, 'basematerials', {'id':'1'})
    # Each object has its own color entry so state and frame remain independently selectable.
    for obj in parts:
        rgba = obj.data.materials[0].diffuse_color
        hexcolor = '#' + ''.join(f'{round(max(0,min(1,c))*255):02X}' for c in rgba)
        sub(materials, 'base', {'name':obj.name, 'displaycolor':hexcolor})
    for oid, obj in enumerate(parts, 2):
        obj.data.calc_loop_triangles()
        item = sub(resources, 'object', {'id':str(oid), 'type':'model', 'name':obj.name, 'pid':'1', 'pindex':str(oid-2)})
        mesh = sub(item, 'mesh')
        vertices = sub(mesh, 'vertices')
        triangles = sub(mesh, 'triangles')
        for vertex in obj.data.vertices:
            p = obj.matrix_world @ vertex.co
            sub(vertices, 'vertex', dict(zip(('x','y','z'), (format(v,'.9g') for v in p))))
        for triangle in obj.data.loop_triangles:
            sub(triangles, 'triangle', dict(zip(('v1','v2','v3'), map(str,triangle.vertices))))
    aid = str(len(parts)+2)
    assembly = sub(resources, 'object', {'id':aid, 'type':'model', 'name':title})
    components = sub(assembly, 'components')
    for oid in range(2, len(parts)+2):
        sub(components, 'component', {'objectid':str(oid)})
    sub(sub(root,'build'), 'item', {'objectid':aid})
    config, project = slicer_metadata(root, title)
    with zipfile.ZipFile(path,'w',zipfile.ZIP_DEFLATED) as archive:
        archive.writestr('[Content_Types].xml', '<?xml version="1.0" encoding="UTF-8"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/></Types>')
        archive.writestr('_rels/.rels','<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Target="/3D/3dmodel.model" Id="rel0" Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/></Relationships>')
        archive.writestr('3D/3dmodel.model', ET.tostring(root,encoding='utf-8',xml_declaration=True))
        archive.writestr('Metadata/model_settings.config', config)
        archive.writestr('Metadata/project_settings.config', json.dumps(project))


def slicer_metadata(root, title):
    """Map component IDs to physical filament slots for Creality/Orca loaders."""
    ns = {'m': 'http://schemas.microsoft.com/3dmanufacturing/core/2015/02'}
    resources = root.find('m:resources', ns)
    assembly = next(o for o in resources.findall('m:object', ns)
                    if o.find('m:components', ns) is not None)
    materials = resources.find('m:basematerials', ns)
    colors, slots = [], {}
    config = ET.Element('config')
    objconfig = ET.SubElement(config, 'object', {'id': assembly.get('id')})
    def meta(parent, key, value):
        ET.SubElement(parent, 'metadata', {'key': key, 'value': str(value)})
    meta(objconfig, 'name', title)
    meta(objconfig, 'extruder', 1)
    objects = {o.get('id'): o for o in resources.findall('m:object', ns)}
    for component in assembly.find('m:components', ns):
        obj = objects[component.get('objectid')]
        color = list(materials)[int(obj.get('pindex'))].get('displaycolor')[:7]
        if color not in slots:
            colors.append(color)
            slots[color] = len(colors)
        part = ET.SubElement(objconfig, 'part', {'id': obj.get('id'), 'subtype': 'normal_part'})
        meta(part, 'name', obj.get('name'))
        meta(part, 'extruder', slots[color])
    plate = ET.SubElement(config, 'plate')
    meta(plate, 'plater_id', 1)
    instance = ET.SubElement(plate, 'model_instance')
    meta(instance, 'object_id', assembly.get('id'))
    meta(instance, 'instance_id', 0)
    meta(instance, 'identify_id', 1)
    # Deliberately leave machine and temperature settings to the user's preset.
    project = {'filament_colour': colors, 'filament_type': ['PLA'] * len(colors),
               'filament_diameter': ['1.75'] * len(colors)}
    return ET.tostring(config, encoding='utf-8', xml_declaration=True), project

def add_avatar_icon(bpy, path):
    """Circular center crop for Blender display only, never a printable part."""
    import math
    image = bpy.data.images.load(str(Path(path).resolve()), check_existing=False)
    image.pack()
    radius, cx, cy, count = 18.4, 21.92, 21.92, 128
    verts = [(cx, cy, 2.01)] + [(cx+radius*math.cos(i*2*math.pi/count), cy+radius*math.sin(i*2*math.pi/count), 2.01) for i in range(count)]
    faces = [(0, i+1, (i+1)%count+1) for i in range(count)]
    mesh = bpy.data.meshes.new('Avatar_Icon')
    mesh.from_pydata(verts, [], faces)
    uv = mesh.uv_layers.new()
    width, height = image.size
    for loop in mesh.loops:
        v = mesh.vertices[loop.vertex_index].co
        uv.data[loop.index].uv = (.5+(v.x-cx)/(2*radius)*min(1,height/width), .5+(v.y-cy)/(2*radius)*min(1,width/height))
    obj = bpy.data.objects.new('Avatar_Icon_Display_Only', mesh)
    bpy.context.collection.objects.link(obj)
    material = bpy.data.materials.new('Avatar_Image')
    material.use_nodes = True
    nodes = material.node_tree.nodes
    tex = nodes.new('ShaderNodeTexImage')
    tex.image = image
    shader = nodes.get('Principled BSDF')
    material.node_tree.links.new(tex.outputs['Color'], shader.inputs['Base Color'])
    material.node_tree.links.new(tex.outputs['Alpha'], shader.inputs['Alpha'])
    obj.data.materials.append(material)
    return obj


def generate(name, status, output_dir, font_path='', open_template=True,
             status_color='auto', only_3mf=True, icon_path=''):
    import bpy
    import bmesh
    name, status = validate(name, status)
    color = resolve_color(status, status_color)
    if icon_path and only_3mf:
        raise ValueError('Avatar images require full export (Blender file). Turn off 3MF only.')
    if icon_path and not Path(icon_path).is_file():
        raise ValueError('Select an existing avatar image.')
    if open_template:
        template = HERE / 'nametag_template.blend'
        if not template.is_file():
            raise FileNotFoundError('Place nametag_template.blend next to this script.')
        bpy.ops.wm.open_mainfile(filepath=str(template))
    # The template supplies the already separated, checked rim and base.
    for obj in list(bpy.data.objects):
        if obj.name.startswith(('Name_', 'State_', 'Avatar_Icon')):
            bpy.data.objects.remove(obj, do_unlink=True)
    rim, base, dot = [bpy.data.objects[n] for n in ('White_Rim','Black_Base','Online_Status_Dot')]
    fonts = [f for f in bpy.data.fonts if f.name != 'Bfont' and f.packed_file]
    font = fonts[0] if fonts else bpy.data.fonts.load(font_path or DEFAULTS['font'])
    def mat(label, color):
        material = bpy.data.materials.get(label) or bpy.data.materials.new(label)
        material.diffuse_color = (*color,1)
        return material
    yellow = mat('Name_Yellow', (1,.78,.025))
    white = mat('White', (.95,.95,.95))
    rim.data.materials.clear()
    rim.data.materials.append(white)
    base.data.materials.clear()
    base.data.materials.append(mat('Black',(.035,.035,.035)))
    text, name_scale = make_text(bpy,'Name_Text',name,46.4,22,55,8.4,font,yellow)
    state, status_scale = make_text(bpy,'State_Text',status,54,13.2,46,5.9,font,white)
    # Left edge aligns with the name; the dot sits immediately before status text.
    from mathutils import Vector
    points = [dot.matrix_world @ v.co for v in dot.data.vertices]
    center_x = (min(p.x for p in points)+max(p.x for p in points))/2
    center_y = (min(p.y for p in points)+max(p.y for p in points))/2
    dot.location += Vector((48.9-center_x, 16.15-center_y, 0))
    bpy.context.view_layer.update()
    dot.data.materials.clear()
    dot.data.materials.append(mat('Status_Color',color))
    parts = [rim,base,text,state,dot]
    if icon_path:
        add_avatar_icon(bpy, icon_path)
    checks = []
    for obj in parts:
        obj.hide_set(False)
        obj.hide_render = False
        bm = bmesh.new()
        bm.from_mesh(obj.data)
        bad = sum(not edge.is_manifold for edge in bm.edges)
        volume = bm.calc_volume()
        bm.free()
        if bad or volume <= 0:
            raise ValueError(f'{obj.name} mesh check failed: {bad} non-manifold edges, volume {volume}. Try another font or text.')
        checks.append({'part':obj.name,'non_manifold_edges':bad,'volume_mm3':volume})
    stem = safe_stem(name,status)
    folder = Path(output_dir).expanduser().resolve() / stem
    # Keep previous runs; never silently overwrite a prior generated version.
    candidate = folder
    revision = 2
    while candidate.exists():
        candidate = folder.with_name(folder.name+f'_{revision}')
        revision += 1
    folder = candidate
    folder.mkdir(parents=True)
    scene = bpy.context.scene
    scene.unit_settings.system = 'METRIC'
    scene.unit_settings.scale_length = .001
    scene.unit_settings.length_unit = 'MILLIMETERS'
    for obj, filename in ([] if only_3mf else zip(parts,('01_White_Rim.stl','02_Black_Base.stl','03_Name.stl','04_Status.stl','05_Status_Dot.stl'))):
        bpy.ops.object.select_all(action='DESELECT')
        obj.select_set(True)
        bpy.context.view_layer.objects.active = obj
        bpy.ops.wm.stl_export(filepath=str(folder/filename),export_selected_objects=True,apply_modifiers=True,use_scene_unit=False)
    export_3mf(bpy,parts,folder/(stem+'.3mf'),name+' / '+status)
    bpy.ops.object.select_all(action='DESELECT')
    for screen in bpy.data.screens:
        for area in screen.areas:
            if area.type == 'VIEW_3D':
                area.spaces.active.shading.color_type = 'MATERIAL'
                if icon_path: area.spaces.active.shading.type = 'MATERIAL'
    if not only_3mf:
        bpy.ops.file.pack_all()
        bpy.ops.wm.save_as_mainfile(filepath=str(folder/(stem+'.blend')))
    report = {'name':name,'status':status,'size_mm':[109.05,43.84,3.6],'parts':checks,'name_scale':name_scale,'status_scale':status_scale}
    if not only_3mf:
        (folder/'mesh_validation.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
    (folder/'PRINTING.txt').write_text(f'Name: {name}\nStatus: {status}\nOpen the 3MF as a project in Creality Print and load filament colors.\nMap colors to actual CFS filaments before printing. Choose printer and material settings, slice and inspect the preview.\nSTL has no color: import all five files as parts of one object.\nThis model is designed for multicolor printing, not separate snap-fit assembly.\nInspect thin strokes when using long text.\n', encoding='utf-8')
    (Path(output_dir).resolve()/'latest_result.json').write_text(json.dumps({'folder':str(folder),'name':name,'status':status},ensure_ascii=False,indent=2),encoding='utf-8')
    if only_3mf:
        (folder/'PRINTING.txt').unlink()
    print('NAMETAG_RESULT='+json.dumps({'folder':str(folder)},ensure_ascii=False),flush=True)
    return folder

def launch_worker(settings, name, status, output_dir):
    name,status = validate(name,status)
    blender = Path(shutil.which(settings['blender']) or settings['blender'])
    if not blender.is_file():
        raise FileNotFoundError('Blender not found. Select blender.exe in the window.')
    command = [str(blender),'--background','--python-exit-code','1','--python',str(Path(__file__).resolve()),'--','--worker','--name',name,'--status',status,'--output',output_dir,'--font',settings.get('font','')]
    command += ['--status-color', settings.get('status_color', 'auto')]
    if not settings.get('only_3mf', True): command.append('--full-export')
    if settings.get('use_icon', False): command += ['--icon', settings.get('icon_path', '')]
    env = dict(os.environ, PYTHONIOENCODING='utf-8', PYTHONUTF8='1')
    result = subprocess.run(command,stdout=subprocess.PIPE,stderr=subprocess.STDOUT,encoding='utf-8',errors='replace',env=env,creationflags=getattr(subprocess,'CREATE_NO_WINDOW',0))
    logs = Path(output_dir)/'last_generation.log'
    logs.parent.mkdir(parents=True,exist_ok=True)
    logs.write_text(result.stdout,encoding='utf-8')
    if result.returncode:
        raise RuntimeError('Generation failed. See '+str(logs)+'\n'+result.stdout[-1600:])
    for line in reversed(result.stdout.splitlines()):
        if line.startswith('NAMETAG_RESULT='):
            return Path(json.loads(line.split('=',1)[1])['folder'])
    raise RuntimeError('Blender returned no result. See '+str(logs))

